import { build, version } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve, relative } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = resolve(import.meta.dirname, '..');
export async function novncBundle() {
  const pkg = JSON.parse(await readFile(resolve(root, 'package.json')));
  const installed = JSON.parse(await readFile(resolve(root, 'node_modules/@novnc/novnc/package.json')));
  if (version !== pkg.devDependencies.esbuild || installed.version !== pkg.optionalDependencies['@novnc/novnc']) throw Error('noVNC 构建工具或源码与锁定版本不符');
  const banner = `/* noVNC ${installed.version}; generated by npm run build:novnc. See novnc-LICENSES.txt.\n * Unmodified library sources: https://registry.npmjs.org/@novnc/novnc/-/novnc-${installed.version}.tgz */`;
  const result = await build({ absWorkingDir: root, entryPoints: ['scripts/novnc-entry.js'], bundle: true, format: 'esm', platform: 'browser',
    target: ['chrome100', 'firefox100', 'safari15.4'], minifyWhitespace: true, minifySyntax: true, minifyIdentifiers: false,
    legalComments: 'inline', charset: 'utf8', write: false, metafile: true, banner: { js: banner }, logLevel: 'silent' });
  const inputs = Object.keys(result.metafile.inputs).sort();
  if (inputs.length > 256 || inputs.some(path => path !== 'scripts/novnc-entry.js' && !path.startsWith('node_modules/@novnc/novnc/')) ||
      Object.values(result.metafile.outputs).some(output => output.imports.length) || result.outputFiles.length !== 1) throw Error('noVNC 构建超出固定依赖集');
  const bundle = result.outputFiles[0].text;
  if (Buffer.byteLength(bundle) > 4 * 1024 * 1024) throw Error('noVNC 包超过资源上限');
  const sha256 = value => createHash('sha256').update(value).digest('hex');
  const sources = [];
  const notices = [];
  for (const path of inputs) {
    const source = await readFile(resolve(root, path), 'utf8'); sources.push({ path, sha256: sha256(source) });
    for (const comment of source.match(/\/\*[\s\S]*?\*\//g) || []) if (/copyright|licensed|permission|redistribution/i.test(comment)) notices.push(path + '\n' + comment);
  }
  for (const path of ['LICENSE.txt', 'AUTHORS', 'docs/LICENSE.MPL-2.0', 'docs/LICENSE.BSD-2-Clause', 'docs/LICENSE.BSD-3-Clause', 'vendor/pako/LICENSE']) {
    notices.push(path + '\n' + await readFile(resolve(root, 'node_modules/@novnc/novnc', path), 'utf8'));
  }
  const licenses = (`noVNC ${installed.version}\nSource: https://registry.npmjs.org/@novnc/novnc/-/novnc-${installed.version}.tgz\n\n` + notices.join('\n\n')).replace(/[\t ]+$/gm, '');
  if (Buffer.byteLength(licenses) > 256 * 1024) throw Error('noVNC 许可记录超过上限');
  const manifest = JSON.stringify({ novnc: installed.version, esbuild: version, sha256: sha256(bundle), inputs: sources }, null, 2) + '\n';
  return { bundle, licenses, manifest };
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const generated = await novncBundle(), directory = resolve(root, 'panel/public/vendor'); await mkdir(directory, { recursive: true });
  for (const [key, name] of Object.entries({ bundle: 'novnc-bundle.js', licenses: 'novnc-LICENSES.txt', manifest: 'novnc-build.json' })) await writeFile(resolve(directory, name), generated[key]);
  console.log(`noVNC bundle: ${Buffer.byteLength(generated.bundle)} bytes (${relative(root, directory)})`);
}
